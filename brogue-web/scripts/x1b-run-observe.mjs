import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
const root=path.resolve(import.meta.dirname,'..');
const evidence=path.join(root,'ai_docs/reports/x-1b-evidence');
const {project}=JSON.parse(fs.readFileSync(path.join(evidence,'stage.json')));
const require=createRequire(import.meta.url);
const {buildSync}=require(path.join(project,'node_modules/esbuild'));
const extra=process.argv.includes('--extra');
const name=extra?'extra':'observe';
const outfile=path.join(project,`x1b-${name}-bundle.mjs`);
const source=fs.readFileSync(path.join(root,`scripts/x1b-${name}.ts`),'utf8');
buildSync({stdin:{contents:source,resolveDir:path.join(project,'scripts'),sourcefile:'x1b-observe.ts',loader:'ts'},outfile,bundle:true,platform:'node',format:'esm',packages:'external',logLevel:'warning'});
const log=fs.createWriteStream(path.join(evidence,extra?'extra-probe.txt':'probe.txt'));
const start=Date.now();
const p=spawn(process.execPath,[outfile,evidence],{cwd:project,windowsHide:true});
for(const s of [p.stdout,p.stderr])s.on('data',b=>{const t=b.toString().replaceAll('\r\n','\n');log.write(t);process.stdout.write(t);});
const code=await new Promise(r=>p.on('close',r));log.end();
fs.writeFileSync(path.join(evidence,extra?'extra-probe-run.json':'probe-run.json'),JSON.stringify({code,seconds:(Date.now()-start)/1000},null,2)+'\n');
process.exitCode=code;
