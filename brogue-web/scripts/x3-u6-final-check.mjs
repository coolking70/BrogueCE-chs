import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import ts from 'typescript';
const out='ai_docs/reports/x3-u6-evidence';
const head=f=>execFileSync('git',['show',`HEAD:brogue-web/${f}`],{encoding:'utf8'});
const sha=b=>createHash('sha256').update(b).digest('hex');
const files=['src/engine/Input.ts','src/components/CommandBar.vue','src/components/ReferenceOverlay.vue','src/components/DPad.vue','package-lock.json'];
for(const f of files)assert.equal(fs.readFileSync(f,'utf8'),head(f),f);
const methodMap=s=>{
 const ast=ts.createSourceFile('Game.ts',s,ts.ScriptTarget.Latest,true);
 const klass=ast.statements.find(n=>ts.isClassDeclaration(n)&&n.name.text==='Game');
 return new Map(klass.members.filter(ts.isMethodDeclaration).map(n=>[n.name.getText(ast),n.getText(ast)]));
};
const before=methodMap(head('src/engine/Core/Game.ts')),after=methodMap(fs.readFileSync('src/engine/Core/Game.ts','utf8'));
const protectedMethods=['manualSearch','searchForSecrets'];
for(const m of protectedMethods)assert.equal(after.get(m),before.get(m),m);
assert.equal(after.get('performPlayerAction').split("} else if (action === 'pickup')")[0],before.get('performPlayerAction').split("} else if (action === 'pickup')")[0],'performPlayerAction before pickup (all stairs/wait/search/move branches)');
const changedMethods=[...after.keys()].filter(k=>before.get(k)!==after.get(k));
const selection=JSON.parse(fs.readFileSync(`${out}/test-selection.json`));
const currentRefs=execFileSync('rg',['-l','-g','*.test.ts','logger|Logger|MessageStrip|Sidebar|acknowledge|hidden door|picked up|status\\.player\\.[a-z_]+_off','src/test'],{encoding:'utf8'}).trim().split('\n');
const missing=currentRefs.filter(f=>!selection.tests.includes(f));assert.deepEqual(missing,[]);
const changed=execFileSync('git',['diff','--name-only'],{encoding:'utf8'}).trim().split('\n').filter(Boolean);
const untracked=execFileSync('git',['ls-files','--others','--exclude-standard'],{encoding:'utf8'}).trim().split('\n').filter(Boolean);
const crlf=[...changed.map(f=>f.replace(/^brogue-web\//,'')),...untracked].filter(f=>fs.existsSync(f)&&!f.endsWith('.gz')&&fs.readFileSync(f).includes(Buffer.from('\r\n')));
assert.deepEqual(crlf,[]);
const pngs=fs.readdirSync(out).filter(f=>f.endsWith('.png')).map(f=>`${out}/${f}`);
for(const f of pngs)execFileSync('git',['check-ignore',f]);
assert.equal(execFileSync('git',['diff','--cached','--name-only'],{encoding:'utf8'}).trim(),'');
execFileSync('git',['diff','--check']);
const golden=Object.fromEntries([2,3,4].map(i=>{const f=`ai_docs/reports/u-r${i}-trace.json${i===2?'':'.gz'}`;return[f,sha(fs.readFileSync(f))];}));
const baselines=Object.fromEntries(['src/test/fixtures/generation_baseline.json','src/test/fixtures/deep_generation_baseline.json'].map(f=>{const equal=fs.readFileSync(f,'utf8')===head(f);assert.equal(equal,true);return[f,equal];}));
const result={protectedFiles:files,protectedMethods,performPlayerAction:'only pickup logging changed; protected prefix byte-identical',changedMethods,selectedTests:selection.tests.length,referenceTests:currentRefs.length,missing,crlf,pngsIgnored:pngs.length,staged:[],generationBaselinesUnchanged:baselines,golden};
fs.writeFileSync(`${out}/final-check.json`,JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result,null,2));
