/** 从枚举取全部成员值（TS 数字枚举的 Object.values 含反向键名，滤掉字符串）。 */
const ALL_TERRAINS: TerrainType[] = Object.values(TerrainType).filter(
    (v): v is TerrainType => typeof v === 'number',
);

/** CE source parsed goldens; generated by scripts/u21c-ce-appearance.mjs. */
const EXPECTED_VISIBLE: Record<TerrainType, { char: string; color: string; bgColor: number | null }> = Object.fromEntries(
    Object.entries(ceTerrainGoldens).map(([name, { char, color, bgColor }]) => [TerrainType[name as keyof typeof TerrainType], { char, color, bgColor }]),
) as Record<TerrainType, { char: string; color: string; bgColor: number | null }>;
const floor = ceTerrainGoldens.FLOOR;
const lightColor = (hex: string, channels: readonly number[]) => '#' + [0, 1, 2].map((i) => {
    const base = parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16);
    const level = Math.max(0, channels[i]!);
    const adjusted = level > 150 ? Math.trunc(Math.sqrt(level / 150) * 150) : level;
    return Math.min(255, Math.trunc(base * adjusted / 100)).toString(16).padStart(2, '0');
}).join('');
const lightBg = (value: number, channels: readonly number[]) => parseInt(lightColor('#' + value.toString(16).padStart(6, '0'), channels).slice(1), 16);

/** 造 Cell（terrain 走 setter 写回归属层）。只用于 DUNGEON/SURFACE 层地形。 */
function makeCell(
    terrain: TerrainType,
    opts: { visible?: boolean; explored?: boolean; memory?: boolean } = {},
): Cell {
    const c = new Cell(3, 4);
    c.terrain = terrain;
    c.isVisible = opts.visible ?? false;
    c.isExplored = opts.explored ?? (opts.visible ?? false);
    c.hasMemory = opts.memory ?? false;
    return c;
}

/** 记录型假幻觉随机：percent 依序弹 percents（弹尽返回 false），pick 恒取首项并记录来源序列。 */
interface ScriptedCosmetic extends CosmeticRng {
    percentCalls: number[];
    pickSources: string[];
}
function scriptedCosmetic(percents: boolean[]): ScriptedCosmetic {
    let i = 0;
    return {
        percentCalls: [],
        pickSources: [],
        percent(p: number) {
            this.percentCalls.push(p);
            return percents[i++] ?? false;
        },
        pick<T>(list: readonly T[]): T {
            this.pickSources.push(list === HALLUCINATION_COLORS ? 'colors' : list === HALLUCINATION_CHARS ? 'chars' : 'other');
            return list[0]!;
        },
    };
}

/** CE 量级的满强白光三通道（矿灯色 {180,180,180} 一类；乘数 1.0 的Identity 光）。 */
const IDENTITY_LIGHT: LightChannels = { r: 100, g: 100, b: 100 };

function cellCtx(overrides: Partial<CellAppearanceContext> = {}): CellAppearanceContext {
    return {
        gas: undefined,
        lightChannels: null,
        groundItem: null,
        carriedItem: null,
        hallucinating: false,
        cosmetic: scriptedCosmetic([]),
        ...overrides,
    };
}

function entityCtx(overrides: Partial<EntityAppearanceContext> = {}): EntityAppearanceContext {
    return {
        cellVisible: true,
        cellHasMemory: false,
        telepathy: false,
        hallucinating: false,
        cosmetic: scriptedCosmetic([]),
        ...overrides,
    };
}

function gas(type: GasType, density = 100): GasCell {
    return { type, density };
}

/** 轻量 Monster 替身：monsterAppearance 只读 hp/isAlly/state/char/color 五个字段。 */
function makeMonster(overrides: Partial<Pick<Monster, 'hp' | 'isAlly' | 'state' | 'char' | 'color'>> = {}): Monster {
    const base = {
        loc: { x: 1, y: 2 },
        hp: 10,
        isAlly: false,
        state: MonsterState.HUNTING,
        char: 'r',
        color: 0xaa0044,
    };
    return { ...base, ...overrides } as unknown as Monster;
}

