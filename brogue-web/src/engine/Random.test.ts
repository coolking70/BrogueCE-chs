describe('Random — 固定 seed 序列锁定（回放系统前置条件）', () => {
    it('seed=987654321 连续 1000 个 randRange(1,100) 与黄金序列完全一致', () => {
        expect(take1000(SEED)).toEqual(GOLDEN_SEQUENCE);
    });

    it('同一 seed 两次初始化产生完全相同的序列', () => {
        const a = take1000(SEED);
        const b = take1000(SEED);
        expect(a).toEqual(b);
        expect(a).toEqual(GOLDEN_SEQUENCE); // 且都与黄金序列一致
    });

    it('不同 seed 产生不同序列（防呆：确认锁的不是常量）', () => {
        expect(take1000(SEED + 1)).not.toEqual(GOLDEN_SEQUENCE);
    });

    it('序列值域在 [1, 100] 且边界可达（均匀性抽查）', () => {
        const seq = GOLDEN_SEQUENCE;
        for (const v of seq) {
            expect(v).toBeGreaterThanOrEqual(1);
            expect(v).toBeLessThanOrEqual(100);
        }
        expect(new Set(seq).size).toBe(100); // 1000 个样本覆盖全部 100 个取值
    });

    it('substantive 计数器与 randRange 调用次数一致（Math.c:164-166）', () => {
        const r = new Random(SEED);
        for (let i = 0; i < 100; i++) r.randRange(1, 100);
        expect(r.randomNumbersGenerated).toBe(100);
    });

    it('randRange 恒定区间时每次消耗 ≥1 个原始随机数（拒绝采样，Math.c:125-136）', () => {
        // 单调性抽查：同 seed 前缀序列不受后续调用影响（无隐藏状态泄漏）
        const r = new Random(SEED);
        const first10 = Array.from({ length: 10 }, () => r.randRange(1, 100));
        expect(first10).toEqual(GOLDEN_SEQUENCE.slice(0, 10));
    });
});
